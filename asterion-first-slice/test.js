const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(__dirname + '/index.html', 'utf8');
const script = html.match(/<script id="asterion-engine">([\s\S]*?)<\/script>/)[1];
const sandbox = { window: {} };
vm.runInNewContext(script, sandbox);
const E = sandbox.window.AsterionCore;
const copy = x => JSON.parse(JSON.stringify(x));

function play(first, second) {
  let s = E.choose(E.create(1000), first, 1000);
  assert.ok(s.pending.durationMs <= 30 * 60 * 1000);
  assert.equal(E.choices(s).length, 0);
  assert.ok(E.reconcile(s, s.pending.dueAt - 1).pending);
  s = E.reconcile(copy(s), s.pending.dueAt);
  assert.equal(s.pending, null);
  assert.equal(s.completedActionIds.length, 1);
  const secondStart = s.log.length;
  s = E.choose(s, second, 1000000);
  assert.ok(s.pending.durationMs <= 30 * 60 * 1000);
  s = E.reconcile(copy(s), s.pending.dueAt);
  assert.equal(s.stage, 'complete');
  assert.equal(s.completedActionIds.length, 2);
  assert.equal(s.log.filter(x=>x.who==='system').length, 1);
  assert.equal(E.reconcile(s, 99999999).log.length, s.log.length);
  assert.ok(s.log.length > secondStart);
  return s;
}
const study = play('watch', 'study');
const take = play('watch', 'take');
const withdraw = play('watch', 'withdraw');
const trace = play('rush', 'trace');
const seam = play('rush', 'force');
const listen = play('listen', 'follownoise');
const knock = play('listen', 'knock');
const hold = play('listen', 'hold');
assert.equal(study.thread, 'none');
assert.equal(take.thread, 'held');
assert.equal(trace.thread, 'none');
assert.notEqual(take.maze, withdraw.maze);
assert.notEqual(knock.maze, hold.maze);
assert.notEqual(seam.location, listen.location);
let s = E.create(2000);
assert.ok(!s.log.some(x => x.text.includes('Daedalus')));
s = E.ask(s, 'why', 2001);
assert.ok(!s.log.some(x => x.text.includes('Daedalus')));
s = E.ask(s, 'builder', 2002);
assert.ok(s.log.some(x => x.text.includes('Daedalus')));
s = E.ask(s, 'proof', 2003);
assert.equal(s.asked.length, 3);
assert.equal(E.ask(s, 'builder', 2004).log.length, s.log.length);
console.log('PASS: eight divergent paths; timing; exactly-once returns; world state; optional lore.');
